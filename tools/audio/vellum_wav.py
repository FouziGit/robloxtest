def output_dir() -> Path:
    root = Path(__file__).resolve().parents[2]
    out = root / "assets" / "audio"
    out.mkdir(parents=True, exist_ok=True)
    return out


def write_wav(path: Path, buf: Buf) -> Path:
    """16-bit PCM mono. Clips at the edge rather than wrapping: an over-range sample wrapped by
    struct is the loudest possible click."""
    frames = bytearray()
    for v in buf.data:
        if v > 1.0:
            v = 1.0
        elif v < -1.0:
            v = -1.0
        frames += struct.pack("<h", int(v * 32767.0))
    data_size = len(frames)
    header = b"RIFF" + struct.pack("<I", 36 + data_size) + b"WAVE"
    fmt = b"fmt " + struct.pack("<IHHIIHH", 16, 1, 1, buf.rate, buf.rate * 2, 2, 16)
    path.write_bytes(header + fmt + b"data" + struct.pack("<I", data_size) + bytes(frames))
    return path


def read_wav_info(path: Path) -> tuple[int, int, int, float]:
    """(rate, channels, bits, seconds), read from the file's own header so verification measures what
    was written and not what the generator meant."""
    head = path.read_bytes()[:44]
    if head[:4] != b"RIFF" or head[8:12] != b"WAVE":
        raise ValueError(f"{path} is not a WAV")
    channels, rate = struct.unpack("<HI", head[22:28])
    bits = struct.unpack("<H", head[34:36])[0]
    data_size = struct.unpack("<I", head[40:44])[0]
    seconds = data_size / (rate * channels * (bits // 8))
    return rate, channels, bits, seconds


def report(paths: list[Path]) -> int:
    over = 0
    for path in paths:
        rate, channels, bits, seconds = read_wav_info(path)
        size = path.stat().st_size
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        flag = ""
        if size > MAX_BYTES:
            over += 1
            flag = f"  OVER BUDGET ({MAX_BYTES} bytes)"
        print(f"{path.name:<28} {rate:>5} Hz {channels}ch {bits}b {seconds:>6.2f}s {size:>8} bytes  {digest}{flag}")
    return over
