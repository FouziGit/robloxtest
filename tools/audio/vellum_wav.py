def semitone(steps: int) -> float:
    """Frequency ratio for `steps` semitones, negative allowed, within three octaves either way. Past the
    table it raises: a clamp here once folded the top of a pentatonic onto one note, and the byte gate was
    happy because the wrong notes reproduced."""
    if abs(steps) >= len(SEMITONE):
        raise ValueError(f"{steps} semitones is outside the table (+/-{len(SEMITONE) - 1})")
    if steps >= 0:
        return SEMITONE[steps]
    return 1.0 / SEMITONE[-steps]


class Rng:
    """SplitMix64, the same eight lines tools/textures/vellum_png.py uses, for the same reason: the
    stream is ours and documented, not the interpreter's."""

    __slots__ = ("_state",)

    def __init__(self, seed: int) -> None:
        self._state = seed & MASK64

    def next_u64(self) -> int:
        self._state = (self._state + 0x9E3779B97F4A7C15) & MASK64
        z = self._state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        return (z ^ (z >> 31)) & MASK64

    def random(self) -> float:
        return (self.next_u64() >> 11) * (1.0 / (1 << 53))

    def uniform(self, low: float, high: float) -> float:
        return low + (high - low) * self.random()

    def signed(self) -> float:
        return self.random() * 2.0 - 1.0


# --- Arithmetic-only trigonometry -------------------------------------------------------------------


def sin(x: float) -> float:
    """sin(x) to better than 4e-6 over any argument, with no libm: range-reduce to [-pi/2, pi/2] by the
    sine's symmetries, then a Taylor polynomial. One 16-bit step is 3e-5, so the error never reaches
    the file."""
    x = x - TWO_PI * int(x / TWO_PI + (0.5 if x >= 0 else -0.5))
    if x > PI / 2:
        x = PI - x
    elif x < -PI / 2:
        x = -PI - x
    x2 = x * x
    return x * (1.0 + x2 * (-1.0 / 6.0 + x2 * (1.0 / 120.0 + x2 * (-1.0 / 5040.0 + x2 * (1.0 / 362880.0 - x2 / 39916800.0)))))


# --- Buffers ----------------------------------------------------------------------------------------


class Buf:
    """A mono float buffer at a fixed rate. Values are nominally -1..1; write() clips."""

    __slots__ = ("rate", "data")

    def __init__(self, rate: int, seconds: float) -> None:
        self.rate = rate
        self.data = [0.0] * max(1, int(rate * seconds + 0.5))

    def __len__(self) -> int:
        return len(self.data)

    def seconds(self) -> float:
        return len(self.data) / self.rate

    def add(self, other: "Buf", at: float = 0.0, gain: float = 1.0) -> "Buf":
        """Mixes `other` in, starting `at` seconds. Past the end is dropped, not extended: a layer that
        outruns its file is a design mistake worth hearing as a cut."""
        start = int(at * self.rate + 0.5)
        data = self.data
        src = other.data
        count = min(len(src), len(data) - start)
        for i in range(count):
            data[start + i] += src[i] * gain
        return self

    def scale(self, gain: float) -> "Buf":
        self.data = [v * gain for v in self.data]
        return self

    def apply(self, env: list[float]) -> "Buf":
        data = self.data
        count = min(len(env), len(data))
        for i in range(count):
            data[i] *= env[i]
        for i in range(count, len(data)):
            data[i] = 0.0
        return self


def silence(rate: int, seconds: float) -> Buf:
    return Buf(rate, seconds)


