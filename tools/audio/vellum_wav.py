"""The audio toolkit every generator in this directory is written with, and nothing else.

docs/JUICE_PLAN.md phase 5 allows two kinds of sound: royalty-free audio whose licence can be shown, or
sound generated by script. Everything Vellum plays is the second kind, for the same reason its textures
are: a file that came from a script is a file whose provenance is the script, and a file that came from
somewhere on the internet is a moderation case waiting to happen. So this module is a synthesiser --
oscillators, noise, envelopes, filters, a delay -- that writes 16-bit mono WAV, and every generator seeds
its own randomness so two runs write the same bytes (scripts/check.sh proves it, the way it proves the
PNGs).

Determinism is the one design constraint that shapes the code. Python's math.sin and math.exp go through
the platform's libm, and two libms can disagree in the last bit; over a million samples that is a flipped
16-bit value somewhere, and a byte-compare gate that fails on CI and passes on a laptop. So the sine here
is a polynomial, envelopes decay by multiplication, and the semitone ratios are literals. Nothing below
calls libm on a per-sample path.

Sound design vocabulary (docs/ART_BIBLE.md): the world is a page and the power is ink. Nothing here is a
laser, an engine or a synth lead. The materials are paper, brush, water, grit, air and the crack of a
quill, and the pigments are told apart by matter as much as by pitch.
"""

from __future__ import annotations

import hashlib
import struct
from pathlib import Path

MASK64 = (1 << 64) - 1

# Sample rates. Effects at 22050: a hit is a transient and its top end is what makes it a hit. Music at
# 16000: a loop is the largest file the client downloads, and a drone with sparse plucks has nothing above
# 8 kHz worth the bytes.
RATE_SFX = 22050
RATE_MUSIC = 16000

# Per-file ceiling. A loop of twenty-four seconds at 16 kHz mono is 768 KB; anything larger is a loop
# that should be shorter, not a budget that should be bigger.
MAX_BYTES = 900 * 1024

PI = 3.141592653589793
TWO_PI = 6.283185307179586

